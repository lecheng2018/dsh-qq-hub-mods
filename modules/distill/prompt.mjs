/**
 * 群友蒸馏 v2 · 高信噪比提炼提示词
 * 目标：只提炼真正可复用的短口癖、语气词、吐槽接话方式；
 * 宁缺毋滥（没好梗直接返回 []），严禁把具体话题台词、产品名、数字攻略或说教模板当口癖。
 */
export function buildDistillPrompt(lines) {
  const formattedChat = lines.map((line, idx) =>
    `[id:${idx + 1}] ${line.name}：${line.text}`
  ).join('\n')

  const task = `从上方这段真实群聊短句中，只挑出**真正可跨话题复用**的群友口癖、语气词或简短接话梗。

【严格标准（宁缺毋滥，没有就返回 []）】
1. **最多输出 3 条**；如果这批消息只是普通问答或聊具体技术/产品，没有任何有辨识度的通用口癖，直接返回空数组 \`[]\`。
2. **只留通用语感，彻底剔除具体内容**：
   - \`situation\`（触发情绪/语境，2~10 字）：写抽象情绪或互动意图，如「觉得离谱」「简短附和」「无语吐槽」「半信半疑」「看乐子」「摆烂放弃」。
   - \`style\`（口癖/短表达，2~12 字）：只写那个短词或极短口语，如「难绷」「确实」「草」「不至于」「真假的」「那没事了」「直接开摆」「6」。
3. **以下内容一条都不要提取（绝对禁止）**：
   - 带任何具体产品/模型/平台/技术词（如 Gemini、GPT、Claude、DeepSeek、反代、节点、会员、套餐、额度、羊毛、鸡蛋、风控、申诉、报错、插件、API 等）。
   - 带任何数字、价格、时长、版本号（如 200刀、0.00x、30天、4.1）。
   - 带「先……再……」「艾特对方」「直接报数字」「无标点短句」「反问句式」这类写作教程/句式分析描述。
   - 迎新欢迎词、机器人/AI 自嘲、客服式建议或长句说教。
   - 个人现实经历（买房、考研、被封号等）。
4. \`source_id\` 必须严格对应上面消息的 \`[id:数字]\` 编号。

【输出格式】
只输出合法 JSON 数组，不要任何解释、标题或代码块外文字：
[
  {"situation": "觉得很离谱", "style": "太难绷了", "source_id": 2},
  {"situation": "懒得折腾放弃", "style": "直接开摆", "source_id": 5}
]`

  return {
    system: '你是极度克制的群聊口癖筛选器。宁可返回 [] 也绝不凑数，只输出纯 JSON 数组。',
    text: `【群聊短句样本】\n${formattedChat}\n\n${task}`,
  }
}
